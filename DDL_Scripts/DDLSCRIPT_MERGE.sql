-- FIXED: Load from location staging table - handling duplicates by taking first occurrence
MERGE INTO DIM_LOCATION AS TARGET
USING (
    SELECT 
        ZIP_CODE,
        FIRST_VALUE(CITY) OVER (PARTITION BY ZIP_CODE ORDER BY CITY) AS CITY,
        FIRST_VALUE(COUNTY) OVER (PARTITION BY ZIP_CODE ORDER BY COUNTY) AS COUNTY,
        FIRST_VALUE(STATE) OVER (PARTITION BY ZIP_CODE ORDER BY STATE) AS STATE,
        FIRST_VALUE(STATE_ABBR) OVER (PARTITION BY ZIP_CODE ORDER BY STATE_ABBR) AS STATE_ABBR,
        FIRST_VALUE(STATE_FIPS) OVER (PARTITION BY ZIP_CODE ORDER BY STATE_FIPS) AS STATE_FIPS
    FROM (
        SELECT DISTINCT
            CAST(ZIPCODE AS VARCHAR(20)) AS ZIP_CODE,
            CITY,
            COUNTY,
            STATE,
            STATE_ABBR,
            STATE_FIPS
        FROM SEATTLE_DW.STAGE.STG_LOCATION
        WHERE ZIPCODE IS NOT NULL AND ZIPCODE != ''
    )
    QUALIFY ROW_NUMBER() OVER (PARTITION BY ZIP_CODE ORDER BY ZIP_CODE) = 1
) AS SOURCE
ON TARGET.ZIP_CODE = SOURCE.ZIP_CODE
WHEN NOT MATCHED THEN
    INSERT (ZIP_CODE, CITY, COUNTY, STATE, STATE_ABBR, STATE_FIPS)
    VALUES (SOURCE.ZIP_CODE, SOURCE.CITY, SOURCE.COUNTY, 
            SOURCE.STATE, SOURCE.STATE_ABBR, SOURCE.STATE_FIPS)
WHEN MATCHED AND (
    COALESCE(TARGET.CITY, '') != COALESCE(SOURCE.CITY, '') OR
    COALESCE(TARGET.COUNTY, '') != COALESCE(SOURCE.COUNTY, '') OR
    COALESCE(TARGET.STATE, '') != COALESCE(SOURCE.STATE, '')
) THEN
    UPDATE SET 
        CITY = SOURCE.CITY,
        COUNTY = SOURCE.COUNTY,
        STATE = SOURCE.STATE,
        STATE_ABBR = SOURCE.STATE_ABBR,
        STATE_FIPS = SOURCE.STATE_FIPS,
        UPDATED_TIMESTAMP = CURRENT_TIMESTAMP();

