USE DATABASE SEATTLE_DW;
USE SCHEMA DW;

-- 1. Check staging data
SELECT COUNT(*) AS STAGING_COUNT FROM SEATTLE_DW.STAGE.STG_PET_LICENSE;

-- 2. Check date formats (first 10 unique dates)
SELECT 
    LICENSE_ISSUE_DATE,
    TRY_TO_DATE(LICENSE_ISSUE_DATE, 'MM/DD/YYYY') AS PARSED_DATE,
    COUNT(*) AS COUNT
FROM SEATTLE_DW.STAGE.STG_PET_LICENSE
GROUP BY LICENSE_ISSUE_DATE
LIMIT 10;

-- 3. Clear fact table
TRUNCATE TABLE FACT_PETLICENSE;

-- 4. WORKING FACT TABLE INSERT
INSERT INTO FACT_PETLICENSE (
    DATE_KEY,
    LOCATION_KEY,
    BREED_KEY,
    PET_KEY,
    LICENSE_NUMBER,
    LICENSE_COUNT
)
SELECT 
    -- Parse date with multiple format attempts
    COALESCE(
        TO_NUMBER(TO_CHAR(TRY_TO_DATE(s.LICENSE_ISSUE_DATE, 'MM/DD/YYYY'), 'YYYYMMDD')),
        TO_NUMBER(TO_CHAR(TRY_TO_DATE(s.LICENSE_ISSUE_DATE, 'M/D/YYYY'), 'YYYYMMDD')),
        TO_NUMBER(TO_CHAR(TRY_TO_DATE(s.LICENSE_ISSUE_DATE, 'YYYY-MM-DD'), 'YYYYMMDD')),
        20200101  -- Default date
    ) AS DATE_KEY,
    
    -- Get Location Key using JOIN instead of subquery
    COALESCE(l.LOCATION_KEY, def_loc.LOCATION_KEY) AS LOCATION_KEY,
    
    -- Get Breed Key using JOIN
    COALESCE(b.BREED_KEY, def_breed.BREED_KEY) AS BREED_KEY,
    
    -- Get Pet Key using JOIN
    COALESCE(p.PET_KEY, def_pet.PET_KEY) AS PET_KEY,
    
    s.LICENSE_NUMBER,
    1 AS LICENSE_COUNT
    
FROM SEATTLE_DW.STAGE.STG_PET_LICENSE s

-- Left join for location
LEFT JOIN DIM_LOCATION l 
    ON TRIM(l.ZIP_CODE) = TRIM(s.ZIP_CODE)

-- Left join for breed (simplified matching)
LEFT JOIN DIM_BREED b 
    ON UPPER(TRIM(COALESCE(b.SPECIES, 'UNKNOWN'))) = UPPER(TRIM(COALESCE(s.SPECIES, 'UNKNOWN')))
    AND UPPER(TRIM(COALESCE(b.PRIMARY_BREED, 'UNKNOWN'))) = UPPER(TRIM(COALESCE(s.PRIMARY_BREED, 'UNKNOWN')))

-- Left join for pet
LEFT JOIN DIM_PET p 
    ON TRIM(p.LICENSE_NUMBER) = TRIM(s.LICENSE_NUMBER)

-- Cross join to get default values
CROSS JOIN (SELECT LOCATION_KEY FROM DIM_LOCATION WHERE ZIP_CODE = '-1' LIMIT 1) def_loc
CROSS JOIN (SELECT MIN(BREED_KEY) AS BREED_KEY FROM DIM_BREED WHERE SPECIES = 'UNKNOWN') def_breed
CROSS JOIN (SELECT PET_KEY FROM DIM_PET WHERE LICENSE_NUMBER = '-1' LIMIT 1) def_pet

WHERE s.LICENSE_NUMBER IS NOT NULL
  AND TRIM(s.LICENSE_NUMBER) != ''
  AND s.LICENSE_ISSUE_DATE IS NOT NULL;

-- 5. Check results
SELECT COUNT(*) AS FACT_COUNT FROM FACT_PETLICENSE;

-- 6. Fixed debug queries (no EXISTS in aggregate)
SELECT 'Debug: Staging records' AS CHECK_TYPE, COUNT(*) AS COUNT
FROM SEATTLE_DW.STAGE.STG_PET_LICENSE
WHERE LICENSE_NUMBER IS NOT NULL;

SELECT 'Debug: Valid dates' AS CHECK_TYPE, COUNT(*) AS COUNT
FROM SEATTLE_DW.STAGE.STG_PET_LICENSE
WHERE TRY_TO_DATE(LICENSE_ISSUE_DATE, 'MM/DD/YYYY') IS NOT NULL;

-- 7. Check dimension matches using JOINs
SELECT 
    'Dimension Matches' AS CHECK_TYPE,
    COUNT(DISTINCT s.LICENSE_NUMBER) AS TOTAL_STAGING,
    COUNT(DISTINCT l.LOCATION_KEY) AS MATCHED_LOCATIONS,
    COUNT(DISTINCT p.PET_KEY) AS MATCHED_PETS,
    COUNT(DISTINCT b.BREED_KEY) AS MATCHED_BREEDS
FROM SEATTLE_DW.STAGE.STG_PET_LICENSE s
LEFT JOIN DIM_LOCATION l ON TRIM(l.ZIP_CODE) = TRIM(s.ZIP_CODE)
LEFT JOIN DIM_PET p ON TRIM(p.LICENSE_NUMBER) = TRIM(s.LICENSE_NUMBER)
LEFT JOIN DIM_BREED b 
    ON UPPER(TRIM(b.SPECIES)) = UPPER(TRIM(s.SPECIES))
    AND UPPER(TRIM(b.PRIMARY_BREED)) = UPPER(TRIM(s.PRIMARY_BREED));

-- 8. If still no data, check if default records exist
SELECT 'Default Records Check' AS CHECK_TYPE;
SELECT 'Location -1' AS RECORD, COUNT(*) AS EXISTS_FLAG FROM DIM_LOCATION WHERE ZIP_CODE = '-1'
UNION ALL
SELECT 'Breed UNKNOWN', COUNT(*) FROM DIM_BREED WHERE SPECIES = 'UNKNOWN'
UNION ALL
SELECT 'Pet -1', COUNT(*) FROM DIM_PET WHERE LICENSE_NUMBER = '-1';