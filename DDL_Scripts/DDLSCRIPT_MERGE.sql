-- 1. DATE DIMENSION (Run First - Independent)
-- =====================================================
MERGE INTO DIM_DATE AS TARGET
USING (
    WITH DATE_RANGE AS (
        SELECT DATEADD(DAY, SEQ4(), '2020-01-01'::DATE) AS FULL_DATE
        FROM TABLE(GENERATOR(ROWCOUNT => 2557))  -- 7 years
    )
    SELECT 
        TO_NUMBER(TO_CHAR(FULL_DATE, 'YYYYMMDD')) AS DATE_KEY,
        FULL_DATE,
        YEAR(FULL_DATE) AS YEAR,
        QUARTER(FULL_DATE) AS QUARTER,
        MONTH(FULL_DATE) AS MONTH,
        MONTHNAME(FULL_DATE) AS MONTH_NAME,
        DAY(FULL_DATE) AS DAY_OF_MONTH,
        DAYOFWEEK(FULL_DATE) AS DAY_OF_WEEK,
        DAYNAME(FULL_DATE) AS DAY_NAME,
        WEEKOFYEAR(FULL_DATE) AS WEEK_OF_YEAR,
        CASE WHEN DAYOFWEEK(FULL_DATE) IN (0, 6) THEN TRUE ELSE FALSE END AS IS_WEEKEND,
        CASE 
            WHEN MONTH(FULL_DATE) >= 10 THEN YEAR(FULL_DATE) + 1
            ELSE YEAR(FULL_DATE)
        END AS FISCAL_YEAR,
        CASE 
            WHEN MONTH(FULL_DATE) IN (10, 11, 12) THEN 1
            WHEN MONTH(FULL_DATE) IN (1, 2, 3) THEN 2
            WHEN MONTH(FULL_DATE) IN (4, 5, 6) THEN 3
            ELSE 4
        END AS FISCAL_QUARTER
    FROM DATE_RANGE
    WHERE FULL_DATE <= '2026-12-31'
) AS SOURCE
ON TARGET.DATE_KEY = SOURCE.DATE_KEY
WHEN NOT MATCHED THEN
    INSERT (DATE_KEY, FULL_DATE, YEAR, QUARTER, MONTH, MONTH_NAME, 
            DAY_OF_MONTH, DAY_OF_WEEK, DAY_NAME, WEEK_OF_YEAR, 
            IS_WEEKEND, FISCAL_YEAR, FISCAL_QUARTER)
    VALUES (SOURCE.DATE_KEY, SOURCE.FULL_DATE, SOURCE.YEAR, SOURCE.QUARTER, 
            SOURCE.MONTH, SOURCE.MONTH_NAME, SOURCE.DAY_OF_MONTH, 
            SOURCE.DAY_OF_WEEK, SOURCE.DAY_NAME, SOURCE.WEEK_OF_YEAR, 
            SOURCE.IS_WEEKEND, SOURCE.FISCAL_YEAR, SOURCE.FISCAL_QUARTER);

