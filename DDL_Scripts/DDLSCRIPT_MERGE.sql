-- 3. BREED DIMENSION (Run Third)
-- =====================================================
-- Add unknown breed for NULL handling
MERGE INTO DIM_BREED AS TARGET
USING (SELECT 'UNKNOWN' AS SPECIES, 'UNKNOWN' AS PRIMARY_BREED, 
              'NONE' AS SECONDARY_BREED, 'UNKNOWN - NONE' AS BREED_COMBINATION, 
              FALSE AS IS_MIXED_BREED) AS SOURCE
ON TARGET.SPECIES = SOURCE.SPECIES 
   AND TARGET.PRIMARY_BREED = SOURCE.PRIMARY_BREED
   AND COALESCE(TARGET.SECONDARY_BREED, 'NONE') = SOURCE.SECONDARY_BREED
WHEN NOT MATCHED THEN
    INSERT (SPECIES, PRIMARY_BREED, SECONDARY_BREED, BREED_COMBINATION, IS_MIXED_BREED)
    VALUES (SOURCE.SPECIES, SOURCE.PRIMARY_BREED, SOURCE.SECONDARY_BREED,
            SOURCE.BREED_COMBINATION, SOURCE.IS_MIXED_BREED);

-- Load from pet staging table
MERGE INTO DIM_BREED AS TARGET
USING (
    SELECT DISTINCT
        UPPER(TRIM(COALESCE(SPECIES, 'UNKNOWN'))) AS SPECIES,
        UPPER(TRIM(COALESCE(PRIMARY_BREED, 'UNKNOWN'))) AS PRIMARY_BREED,
        UPPER(TRIM(COALESCE(NULLIF(SECONDARY_BREED, ''), 'NONE'))) AS SECONDARY_BREED,
        UPPER(TRIM(COALESCE(PRIMARY_BREED, 'UNKNOWN'))) || ' - ' || 
            UPPER(TRIM(COALESCE(NULLIF(SECONDARY_BREED, ''), 'NONE'))) AS BREED_COMBINATION,
        CASE 
            WHEN SECONDARY_BREED IS NOT NULL 
                 AND TRIM(SECONDARY_BREED) != '' 
                 AND UPPER(TRIM(SECONDARY_BREED)) NOT IN ('NONE', 'NULL')
            THEN TRUE 
            ELSE FALSE 
        END AS IS_MIXED_BREED
    FROM SEATTLE_DW.STAGE.STG_PET_LICENSE
) AS SOURCE
ON TARGET.SPECIES = SOURCE.SPECIES 
   AND TARGET.PRIMARY_BREED = SOURCE.PRIMARY_BREED
   AND COALESCE(TARGET.SECONDARY_BREED, 'NONE') = COALESCE(SOURCE.SECONDARY_BREED, 'NONE')
WHEN NOT MATCHED THEN
    INSERT (SPECIES, PRIMARY_BREED, SECONDARY_BREED, BREED_COMBINATION, IS_MIXED_BREED)
    VALUES (SOURCE.SPECIES, SOURCE.PRIMARY_BREED, SOURCE.SECONDARY_BREED,
            SOURCE.BREED_COMBINATION, SOURCE.IS_MIXED_BREED)
WHEN MATCHED AND (
    TARGET.BREED_COMBINATION != SOURCE.BREED_COMBINATION OR
    TARGET.IS_MIXED_BREED != SOURCE.IS_MIXED_BREED
) THEN
    UPDATE SET 
        BREED_COMBINATION = SOURCE.BREED_COMBINATION,
        IS_MIXED_BREED = SOURCE.IS_MIXED_BREED,
        UPDATED_TIMESTAMP = CURRENT_TIMESTAMP();

